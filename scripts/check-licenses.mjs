#!/usr/bin/env node
/**
 * npm dependency licence record and allowlist (B-026, guardrail 13).
 * Reads package-lock.json (lockfile v2/v3 records each package's licence), so it
 * needs no extra packages and no network.
 *
 *   node scripts/check-licenses.mjs            # check: exit 1 on a denied licence in runtime deps
 *   node scripts/check-licenses.mjs --write    # also regenerate the npm section of docs/LICENSES.md
 *
 * Policy
 *   deny    GPL / AGPL / SSPL in runtime (non-dev) packages. GPL code belongs in a
 *           separate research service, never linked into the core.
 *   review  LGPL, Hippocratic, FSL, CC-BY, UNKNOWN: listed for a human/legal decision.
 *   allow   everything matching ALLOW below.
 * Python licences are checked in CI with pip-licenses (see .github/workflows/ci.yml).
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const ALLOW = /^(MIT|MIT-0|ISC|0BSD|BSD|BSD-2-Clause|BSD-3-Clause|Apache-2\.0|BlueOak-1\.0\.0|CC0-1\.0|Unlicense|Python-2\.0|Zlib|WTFPL|AFL-2\.1)$/;
const DENY = /\b(A?GPL|SSPL)/; // matches GPL-*, AGPL-*, not LGPL (checked first)
const LGPL = /\bLGPL/;

export function classify(expr) {
  const lic = (expr || 'UNKNOWN').trim();
  // SPDX "OR": acceptable if any alternative is allowed.
  const orParts = lic.replace(/^\(|\)$/g, '').split(/\s+OR\s+/i);
  if (orParts.length > 1 && orParts.some((p) => ALLOW.test(p.trim()))) return 'allow';
  // SPDX "AND": every part applies.
  const andParts = lic.replace(/^\(|\)$/g, '').split(/\s+AND\s+/i).map((p) => p.trim());
  if (andParts.some((p) => !LGPL.test(p) && DENY.test(p))) return 'deny';
  if (andParts.every((p) => ALLOW.test(p))) return 'allow';
  return 'review';
}

export function collect(lock) {
  const rows = [];
  for (const [key, meta] of Object.entries(lock.packages ?? {})) {
    if (!key) continue; // root project
    const name = meta.name ?? key.slice(key.lastIndexOf('node_modules/') + 'node_modules/'.length);
    rows.push({
      name,
      version: meta.version ?? '',
      license: typeof meta.license === 'string' ? meta.license : 'UNKNOWN',
      dev: Boolean(meta.dev),
      optional: Boolean(meta.optional || meta.devOptional),
      klass: classify(typeof meta.license === 'string' ? meta.license : 'UNKNOWN'),
    });
  }
  return rows;
}

function renderNpmSection(rows) {
  const runtime = rows.filter((r) => !r.dev);
  const counts = {};
  for (const r of runtime) counts[r.license] = (counts[r.license] ?? 0) + 1;
  const review = rows.filter((r) => r.klass !== 'allow');
  const lines = [];
  lines.push('<!-- BEGIN npm (generated by `node scripts/check-licenses.mjs --write`; do not edit by hand) -->');
  lines.push('');
  lines.push(`Runtime packages: ${runtime.length}. Dev-only packages: ${rows.length - runtime.length}. Source: \`package-lock.json\`.`);
  lines.push('');
  lines.push('| Licence (runtime packages) | Count |');
  lines.push('| --- | ---: |');
  for (const [lic, n] of Object.entries(counts).sort((a, b) => b[1] - a[1])) lines.push(`| ${lic} | ${n} |`);
  lines.push('');
  lines.push('Packages outside the allowlist (runtime and dev):');
  lines.push('');
  lines.push('| Package | Version | Licence | Scope | Status |');
  lines.push('| --- | --- | --- | --- | --- |');
  for (const r of review.sort((a, b) => a.name.localeCompare(b.name))) {
    const scope = r.dev ? 'dev' : r.optional ? 'runtime (optional)' : 'runtime';
    lines.push(`| \`${r.name}\` | ${r.version} | ${r.license} | ${scope} | ${r.klass === 'deny' ? '**DENY**' : 'review'} |`);
  }
  lines.push('');
  lines.push('<!-- END npm -->');
  return lines.join('\n');
}

function main() {
  const lock = JSON.parse(readFileSync('package-lock.json', 'utf8'));
  const rows = collect(lock);
  const denied = rows.filter((r) => r.klass === 'deny' && !r.dev);

  if (process.argv.includes('--write')) {
    const path = 'docs/LICENSES.md';
    const section = renderNpmSection(rows);
    const current = existsSync(path) ? readFileSync(path, 'utf8') : '';
    const re = /<!-- BEGIN npm[\s\S]*?<!-- END npm -->/;
    if (!re.test(current)) {
      console.error(`${path} has no npm markers; add <!-- BEGIN npm --> ... <!-- END npm --> first.`);
      process.exit(2);
    }
    writeFileSync(path, current.replace(re, section));
    console.log(`licenses: wrote npm section of ${path}`);
  }

  const review = rows.filter((r) => r.klass === 'review' && !r.dev);
  for (const r of review) console.log(`::warning title=licence-review::${r.name}@${r.version} is ${r.license} (needs review, see docs/LICENSES.md)`);
  if (denied.length) {
    for (const r of denied) console.log(`::error title=licence-deny::${r.name}@${r.version} is ${r.license}; GPL/AGPL is not allowed in the core (guardrail 13)`);
    process.exit(1);
  }
  console.log(`licenses: OK (${rows.length} packages, ${review.length} runtime package(s) flagged for review, 0 denied)`);
}

main();
